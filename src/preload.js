// A ponte entre a página e o processo principal: só estas chamadas, nada mais do Node chega à página.
const { contextBridge, ipcRenderer } = require('electron');

const invoke = (channel) => (...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('estaleiro', {
  app: { info: invoke('app:info'), openPath: invoke('app:open-path') },
  agents: {
    list: invoke('agents:list'),
    pickFolder: invoke('agents:pick-folder'),
    scan: invoke('agents:scan'),
    add: invoke('agents:add'),
    setStep: invoke('agents:set-step'),
    move: invoke('agents:move'),
    setPause: invoke('agents:set-pause'),
    remove: invoke('agents:remove'),
    setRunner: invoke('agents:set-runner'),
    readFile: invoke('agents:read-file'),
    reveal: invoke('agents:reveal'),
  },
  settings: {
    get: invoke('settings:get'),
    setRoot: invoke('settings:set-root'),
    pickRoot: invoke('settings:pick-root'),
  },
  services: {
    list: invoke('services:list'),
    refresh: invoke('services:refresh'),
  },
  tasks: {
    list: invoke('tasks:list'),
    get: invoke('tasks:get'),
    create: invoke('tasks:create'),
    pickFiles: invoke('tasks:pick-files'),
    pickFolder: invoke('tasks:pick-folder'),
    addDocuments: invoke('tasks:add-documents'),
    uploadDocuments: invoke('tasks:upload-documents'),
    setServices: invoke('tasks:set-services'),
    addStepInputs: invoke('tasks:add-step-inputs'),
    uploadStepInputs: invoke('tasks:upload-step-inputs'),
    removeStepInput: invoke('tasks:remove-step-input'),
    removeDocument: invoke('tasks:remove-document'),
    readDocument: invoke('tasks:read-document'),
    removeDocumentFile: invoke('tasks:remove-document-file'),
    revealDocument: invoke('tasks:reveal-document'),
    documentBytes: invoke('tasks:document-bytes'),
    replaceDocument: invoke('tasks:replace-document'),
    addToFolder: invoke('tasks:add-to-folder'),
    remove: invoke('tasks:remove'),
  },
  pipeline: {
    start: invoke('pipeline:start'),
    send: invoke('pipeline:send'),
    models: invoke('pipeline:models'),
    answer: invoke('pipeline:answer'),
    done: invoke('pipeline:done'),
    stop: invoke('pipeline:stop'),
    continue: invoke('pipeline:continue'),
    retry: invoke('pipeline:retry'),
    resume: invoke('pipeline:resume'),
    console: invoke('pipeline:console'),
    outputs: invoke('pipeline:outputs'),
    readOutput: invoke('pipeline:read-output'),
    changes: invoke('pipeline:changes'),
    scanRepos: invoke('pipeline:scan-repos'),
    setBranch: invoke('pipeline:set-branch'),
    fileDiff: invoke('pipeline:file-diff'),
    inputs: invoke('pipeline:inputs'),
    setInputs: invoke('pipeline:set-inputs'),
    readInput: invoke('pipeline:read-input'),
    setAgentSettings: invoke('pipeline:set-agent-settings'),
    alertResolve: invoke('pipeline:alert-resolve'),
    alertDismiss: invoke('pipeline:alert-dismiss'),
  },
  onTaskEvent: (cb) => ipcRenderer.on('task-event', (_, e) => cb(e)),
});
